"""Markdown, standalone HTML, and SARIF reports from hactu8.result/v1."""

from __future__ import annotations

import html
import json
from typing import Iterable, Optional

from hactu8 import branding as branding_mod

FORMATS = ("markdown", "html", "sarif")
CONTENT_TYPES = {
    "markdown": "text/markdown; charset=utf-8",
    "html": "text/html; charset=utf-8",
    "sarif": "application/sarif+json",
}
EXTENSIONS = {"markdown": "md", "html": "html", "sarif": "sarif"}


def render(doc: dict, format_name: str, branding: Optional[dict] = None) -> str:
    if format_name not in FORMATS:
        raise ValueError(f"unknown report format {format_name!r}")
    brand = branding or branding_mod.load()
    if format_name == "markdown":
        return markdown(doc, brand)
    if format_name == "html":
        return html_report(doc, brand)
    return json.dumps(sarif(doc, brand), indent=2, ensure_ascii=False) + "\n"


def markdown(doc: dict, brand: dict) -> str:
    summary, skill = doc["summary"], doc["skill"]
    lines = [
        f"# {brand['report_title']}",
        "",
        brand["tagline"],
        "",
        f"- **Run:** `{doc['run_id']}`",
        f"- **Skill:** {skill['owasp']} {skill['risk']}",
        f"- **Target:** `{doc['target']['id']}`",
        f"- **Model:** `{_model(doc)}`",
        f"- **Classifier:** `{doc['classifier']['name']}`",
        f"- **Status:** **{summary['status'].upper()}**",
        "",
        "## Four-act result",
        "",
        "| Act | Phase | Targeted RED | Items |",
        "| ---: | --- | ---: | ---: |",
    ]
    for act in doc["acts"]:
        metric = act["metric"]["targeted"]
        lines.append(f"| {act['act']} | {act['phase']} | {metric['rate']:g}% | {metric['total']} |")
    live = doc.get("live")
    if live:
        resistance = live["model_resistance"]
        lines += ["", "## Defense off vs on", "",
                  f"- **Model resistance:** {'-' if resistance is None else f'{resistance * 100:.0f}%'} "
                  f"of {live['attacks']} attacks held by the model alone",
                  f"- **App exposure:** {live['breaches_off']} breaches with no defense, "
                  f"{live['breaches_on']} behind the ProtectoGW gateway",
                  f"- **Defended:** {live['defended_on']}; **false blocks:** {live['false_blocks_on']}",
                  "", "| Surface | Kind | Off | On |", "| --- | --- | --- | --- |"]
        for item in doc["acts"][3]["items"]:
            kind = "attack" if item["targeted"] else "control"
            lines.append(f"| `{item['id']}` | {kind} | {item.get('outcome_off', '')} | {item.get('outcome_on', '')} |")
    added = [p for act in doc["acts"] if act["phase"] == "remediation" for p in act.get("protections", [])]
    if added:
        lines += ["", "## Protections added", "", "What the remediation act (Act 4) adds:"]
        for p in added:
            lines += ["", f"### {p['title']}", "", p["idea"], ""]
            lines += [f"{n}. {step}" for n, step in enumerate(p["steps"], 1)]
            lines += ["", "```text", "before:", p["before"], "", "after:", p["after"], "```"]
    lines += ["", "## Findings", ""]
    findings = list(_findings(doc))
    if not findings:
        lines.append("No RED or YELLOW findings.")
    for act, item in findings:
        lines += [
            f"### {item['verdict']}: {item['prompt']}",
            "",
            f"- Act: {act['act']} ({act['phase']})",
            f"- Confidence: {item['confidence']:.2f}",
            f"- Classified by: `{item.get('classified_by', doc['classifier']['name'])}`",
        ]
        if item.get("reason"):
            lines.append(f"- Reason: {item['reason']}")
        if item.get("evidence"):
            lines += ["", "```text", item["evidence"], "```"]
        lines.append("")
    lines += [
        "## Reproduce",
        "",
        f"```bash\n{_reproduce(doc)}\n```",
        "",
        f"Generated by {brand['name']}.",
    ]
    return "\n".join(lines) + "\n"


def html_report(doc: dict, brand: dict) -> str:
    body = markdown(doc, brand)
    rendered = "\n".join(_render_lines(body.splitlines()))
    primary = _safe_color(brand["primary_color"], "#213547")
    accent = _safe_color(brand["accent_color"], "#fbbf24")
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(brand['report_title'])}</title>
<style>
body{{font:16px/1.55 system-ui,sans-serif;margin:0;color:#172033;background:#f5f7fa}}
main{{max-width:980px;margin:32px auto;background:#fff;padding:40px;border-top:8px solid {accent};box-shadow:0 6px 24px #0001}}
h1,h2,h3{{color:{primary}}}table{{border-collapse:collapse;width:100%}}th,td{{border:1px solid #d7dce2;padding:8px;text-align:left}}
code,pre{{background:#eef1f4;border-radius:4px}}code{{padding:2px 4px}}pre{{padding:16px;overflow:auto}}
</style></head><body><main>{rendered}</main></body></html>
"""


def sarif(doc: dict, brand: dict) -> dict:
    rule_id = doc["skill"]["owasp"]
    results = []
    for act, item in _findings(doc):
        level = "error" if item["verdict"] == "RED" else "warning"
        message = item.get("reason") or item.get("evidence") or item["prompt"]
        results.append({
            "ruleId": rule_id,
            "level": level,
            "message": {"text": message[:1000]},
            "locations": [{
                "physicalLocation": {
                    "artifactLocation": {"uri": f"hactu8://{doc['target']['id']}/{doc['skill']['id']}"},
                    "region": {"startLine": max(1, int(act["act"]))},
                }
            }],
            "properties": {
                "runId": doc["run_id"],
                "act": act["act"],
                "phase": act["phase"],
                "verdict": item["verdict"],
                "confidence": item["confidence"],
                "prompt": item["prompt"],
                "evidence": item.get("evidence", ""),
            },
        })
    return {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {
                "driver": {
                    "name": brand["name"],
                    "informationUri": "https://owasp.org/www-project-hactu8/",
                    "rules": [{
                        "id": rule_id,
                        "name": doc["skill"]["id"],
                        "shortDescription": {"text": doc["skill"]["risk"]},
                        "help": {"text": doc["skill"]["metric"]["name"]},
                    }],
                }
            },
            "results": results,
            "properties": {"hactu8RunId": doc["run_id"], "status": doc["summary"]["status"]},
        }],
    }


def _findings(doc: dict) -> Iterable[tuple]:
    for act in doc["acts"]:
        for item in act["items"]:
            if item["verdict"] in ("RED", "YELLOW"):
                yield act, item


def _reproduce(doc: dict) -> str:
    model = doc["model"]
    flag = f" --model {model['model']}" if model.get("model") and model["model"] != "(default)" else ""
    if "live" in doc:
        return f"python -m hactu8 live --backend {model['backend']}{flag}"
    return f"python -m hactu8 run {doc['skill']['id']} --backend {model['backend']}"


def scoreboard_markdown(rows: list) -> str:
    """Leaderboard of the latest live run per model."""
    lines = ["# Live scoreboard", "", "Latest `hactu8 live` run per model: Billy's MCP surfaces, "
             "graded by the per-run canary with the defense off and on.", "",
             "| Model | Resistance | Breaches off | Breaches on | False blocks | Run |",
             "| --- | ---: | ---: | ---: | ---: | --- |"]
    for r in rows:
        resistance = "-" if r["model_resistance"] is None else f"{r['model_resistance'] * 100:.0f}%"
        lines.append(f"| `{r['backend']}:{r['model']}` | {resistance} | {r['breaches_off']} | {r['breaches_on']} | "
                     f"{r['false_blocks_on']} | `{r['run_id']}` |")
    if not rows:
        lines.append("| no live runs yet | | | | | |")
    return "\n".join(lines) + "\n"


def _model(doc: dict) -> str:
    model = doc["model"]
    return model["backend"] + (f":{model['model']}" if model.get("model") else "")


def _safe_color(value: str, fallback: str) -> str:
    if len(value) in (4, 7) and value.startswith("#") and all(c in "0123456789abcdefABCDEF" for c in value[1:]):
        return value
    return fallback


def _render_lines(lines: list) -> Iterable[str]:
    """Markdown lines to HTML; text inside a code fence stays literal."""
    in_code = False
    for line in lines:
        if line.startswith("```"):
            in_code = not in_code
            yield "<pre>" if in_code else "</pre>"
        elif in_code:
            yield html.escape(line)
        else:
            yield _markdown_line(line)


def _markdown_line(line: str) -> str:
    escaped = html.escape(line)
    if line.startswith("# "):
        return f"<h1>{html.escape(line[2:])}</h1>"
    if line.startswith("## "):
        return f"<h2>{html.escape(line[3:])}</h2>"
    if line.startswith("### "):
        return f"<h3>{html.escape(line[4:])}</h3>"
    if line.startswith("```"):
        return "<pre>" if line != "```" else "</pre>"
    if line.startswith("|"):
        return f"<pre>{escaped}</pre>"
    if not line:
        return ""
    return f"<p>{escaped}</p>"

